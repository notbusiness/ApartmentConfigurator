"""Creates the two master materials used by the configurator.

Run from the command line (the editor must be closed):
    UnrealEditor-Cmd.exe ApartmentConfigurator.uproject -run=pythonscript -script="<abs path>/Tools/CreateMaterials.py"

Materials are generated by script so they are reproducible and reviewable as text:
  /Game/Configurator/Materials/M_ConfiguratorSurface  - opaque, lit, procedural surface detail
  /Game/Configurator/Materials/M_ConfiguratorOverlay  - translucent, unlit: Color, Emissive, Opacity
C++ creates dynamic instances of them and sets the parameters (see BuildingArchitectureComponent.cpp).

M_ConfiguratorSurface parameters:
  Color, Roughness, Metallic - base look
  Pattern  - which procedural surface to draw (see SURFACE_HLSL): 0 plain, 1 plaster, 2 brick,
             3 paving, 4 grass, 5 asphalt/roofing, 6 window glass, 7 foliage, 8 concrete, 9 distant buildings
  Origin, Yaw - actor location and yaw (radians): patterns are laid out in actor space,
                so bricks stay aligned with the walls when the building is rotated
  Bump     - strength of the procedural relief
No textures are used: colour variation and relief are computed in the shader from the position.
"""
import unreal

FOLDER = "/Game/Configurator/Materials"
mel = unreal.MaterialEditingLibrary
assets = unreal.EditorAssetLibrary
tools = unreal.AssetToolsHelpers.get_asset_tools()

SURFACE_HLSL = r"""
struct FSurfaceNoise
{
    float Hash21(float2 p)
    {
        p = frac(p * float2(123.34, 456.21));
        p += dot(p, p + 45.32);
        return frac(p.x * p.y);
    }
    float Hash31(float3 p)
    {
        p = frac(p * float3(0.1031, 0.1030, 0.0973));
        p += dot(p, p.yxz + 33.33);
        return frac((p.x + p.y) * p.z);
    }
    float Noise2(float2 p)
    {
        float2 i = floor(p);
        float2 f = frac(p);
        f = f * f * (3.0 - 2.0 * f);
        float a = Hash21(i);
        float b = Hash21(i + float2(1, 0));
        float c = Hash21(i + float2(0, 1));
        float d = Hash21(i + float2(1, 1));
        return lerp(lerp(a, b, f.x), lerp(c, d, f.x), f.y);
    }
    float Noise3(float3 p)
    {
        float3 i = floor(p);
        float3 f = frac(p);
        f = f * f * (3.0 - 2.0 * f);
        float n000 = Hash31(i);
        float n100 = Hash31(i + float3(1, 0, 0));
        float n010 = Hash31(i + float3(0, 1, 0));
        float n110 = Hash31(i + float3(1, 1, 0));
        float n001 = Hash31(i + float3(0, 0, 1));
        float n101 = Hash31(i + float3(1, 0, 1));
        float n011 = Hash31(i + float3(0, 1, 1));
        float n111 = Hash31(i + float3(1, 1, 1));
        return lerp(lerp(lerp(n000, n100, f.x), lerp(n010, n110, f.x), f.y),
                    lerp(lerp(n001, n101, f.x), lerp(n011, n111, f.x), f.y), f.z);
    }
    float Fbm2(float2 p)
    {
        return 0.5 * Noise2(p) + 0.3 * Noise2(p * 2.13) + 0.2 * Noise2(p * 4.37);
    }
};
FSurfaceNoise F;

// Actor space: patterns follow the building when it is rotated.
float SinYaw = sin(-Yaw);
float CosYaw = cos(-Yaw);
float3 L = float3(P.x * CosYaw - P.y * SinYaw, P.x * SinYaw + P.y * CosYaw, P.z);
float3 NL = float3(N.x * CosYaw - N.y * SinYaw, N.x * SinYaw + N.y * CosYaw, N.z);

// Planar projection along the dominant axis of the surface normal (all geometry is boxes).
float3 AbsN = abs(NL);
float2 UV = (AbsN.z > 0.5) ? L.xy : ((AbsN.x > AbsN.y) ? L.yz : L.xz);

// Pixel footprint in cm: fine detail fades out before it turns into noise at a distance.
float Foot = max(length(ddx(P)), length(ddy(P)));

float3 Col = BaseColor;
float R = Rough;
float M = Metal;
float H = 0.0;          // height field for the relief
float BumpScale = 0.0;
int Pat = (int)round(Pattern);

if (Pat == 1)           // plaster
{
    float Large = F.Fbm2(UV / 45.0);
    float Grain = F.Noise2(UV / 2.5);
    Col *= 0.93 + 0.12 * Large;
    Col *= 0.97 + 0.06 * Grain * saturate(1.0 - Foot / 3.0);
    H = Grain * 0.6 + F.Noise2(UV / 0.8) * 0.4;
    BumpScale = 0.35 * saturate(1.0 - Foot / 2.0);
    R = saturate(R + (Large - 0.5) * 0.1);
}
else if (Pat == 2)      // brick, running bond
{
    float2 Size = float2(25.0, 7.5);
    float Row = floor(UV.y / Size.y);
    float Shift = (fmod(abs(Row), 2.0) > 0.5) ? Size.x * 0.5 : 0.0;
    float2 Q = float2(UV.x + Shift, UV.y) / Size;
    float2 Id = floor(Q);
    float2 Fq = frac(Q);
    float2 Edge = min(Fq, 1.0 - Fq) * Size;
    float Mortar = 1.0 - smoothstep(0.35, 0.9, min(Edge.x, Edge.y));
    float Fade = saturate(1.0 - Foot / 4.0);
    float Var = F.Hash21(Id);
    float3 Brick = BaseColor * (0.78 + 0.45 * Var) * (0.92 + 0.16 * F.Noise2(UV / 1.7));
    float3 MortarColor = float3(0.42, 0.40, 0.37);
    // Far away the wall turns into the average of bricks and mortar, so its tone does not jump with distance.
    Col = lerp(lerp(BaseColor, MortarColor, 0.2), lerp(Brick, MortarColor, Mortar), Fade);
    H = (1.0 - Mortar) * (0.85 + 0.15 * Var);
    BumpScale = 1.2 * Fade;
    R = lerp(R, 0.95, Mortar * Fade);
}
else if (Pat == 3)      // paving slabs
{
    float2 Size = float2(60.0, 30.0);
    float Row = floor(UV.y / Size.y);
    float Shift = (fmod(abs(Row), 2.0) > 0.5) ? Size.x * 0.5 : 0.0;
    float2 Q = float2(UV.x + Shift, UV.y) / Size;
    float2 Id = floor(Q);
    float2 Fq = frac(Q);
    float2 Edge = min(Fq, 1.0 - Fq) * Size;
    float Joint = 1.0 - smoothstep(0.3, 0.8, min(Edge.x, Edge.y));
    float Fade = saturate(1.0 - Foot / 8.0);
    float Var = F.Hash21(Id);
    float3 Slab = BaseColor * (0.86 + 0.28 * Var) * (0.95 + 0.1 * F.Noise2(UV / 3.0));
    Col = lerp(BaseColor, lerp(Slab, BaseColor * 0.45, Joint), Fade);
    H = 1.0 - Joint;
    BumpScale = 0.8 * Fade;
}
else if (Pat == 4)      // lawn
{
    float Patches = F.Fbm2(UV / 400.0);
    float Mid = F.Fbm2(UV / 35.0);
    float Blades = F.Noise2(UV / 2.0);
    Col = BaseColor * (0.7 + 0.6 * Patches) * (0.8 + 0.4 * Mid);
    Col = lerp(Col, Col * float3(1.25, 1.15, 0.6), saturate(Patches * Mid * 1.5 - 0.35));
    Col *= 0.9 + 0.2 * Blades * saturate(1.0 - Foot / 3.0);
    H = Blades;
    BumpScale = 0.5 * saturate(1.0 - Foot / 2.0);
}
else if (Pat == 5)      // asphalt / roofing felt
{
    float Stains = F.Fbm2(UV / 250.0);
    float Grit = F.Noise2(UV / 0.9);
    Col = BaseColor * (0.8 + 0.4 * Stains) * (0.85 + 0.3 * Grit * saturate(1.0 - Foot / 2.0));
    H = Grit;
    BumpScale = 0.5 * saturate(1.0 - Foot / 1.5);
    R = saturate(R - 0.15 * Stains);
}
else if (Pat == 6)      // window glass: every window (instance) looks a little different
{
    float V = frac(InstRand * 7.31 + 0.13);
    float Curtain = step(0.62, V);
    Col = lerp(BaseColor * (0.6 + 0.8 * V), float3(0.55, 0.53, 0.48), Curtain * 0.55);
    R = lerp(R, 0.2, Curtain * 0.5);
    M = lerp(M, 0.1, Curtain * 0.7);
}
else if (Pat == 7)      // foliage
{
    float Clumps = F.Noise3(P / 38.0);
    float Leaves = F.Noise3(P / 11.0);
    Col = BaseColor * (0.55 + 0.9 * Clumps) * (0.8 + 0.4 * Leaves) * (0.85 + 0.3 * InstRand);
    Col = lerp(Col, Col * float3(1.3, 1.25, 0.7), saturate(Clumps - 0.55) * 1.2);
    H = Clumps * 0.7 + Leaves * 0.3;
    BumpScale = 14.0 * saturate(1.0 - Foot / 12.0);
}
else if (Pat == 8)      // concrete
{
    float Large = F.Fbm2(UV / 60.0);
    float Grain = F.Noise2(UV / 1.5);
    float Streaks = F.Noise2(float2(UV.x / 12.0, UV.y / 220.0));
    Col = BaseColor * (0.88 + 0.2 * Large) * (0.94 + 0.12 * Streaks);
    Col *= 0.97 + 0.06 * Grain * saturate(1.0 - Foot / 2.0);
    H = Grain;
    BumpScale = 0.3 * saturate(1.0 - Foot / 1.5);
}
else if (Pat == 9)      // distant buildings: a grid of windows on a plain volume
{
    float2 Cell = float2(330.0, 300.0);
    float2 Q = UV / Cell;
    float2 Id = floor(Q);
    float2 Fq = frac(Q);
    float Window = step(0.22, Fq.x) * step(Fq.x, 0.78) * step(0.3, Fq.y) * step(Fq.y, 0.8) * step(AbsN.z, 0.5);
    float Lit = F.Hash21(Id);
    float3 Glass = lerp(float3(0.05, 0.07, 0.10), float3(0.18, 0.22, 0.27), Lit);
    Col = lerp(BaseColor * (0.92 + 0.12 * F.Hash21(Id.yy + 3.0)), Glass, Window);
    R = lerp(R, 0.15, Window);
    M = lerp(M, 0.5, Window);
}

// Relief from the height field using screen-space derivatives (no tangent basis or textures needed).
float3 Nw = normalize(N);
if (BumpScale * Bump > 0.001)
{
    float3 DpDx = ddx(P);
    float3 DpDy = ddy(P);
    float DhDx = ddx(H);
    float DhDy = ddy(H);
    float3 R1 = cross(DpDy, Nw);
    float3 R2 = cross(Nw, DpDx);
    float Det = dot(DpDx, R1);
    float3 Gradient = sign(Det) * (DhDx * R1 + DhDy * R2);
    Nw = normalize(abs(Det) * Nw - BumpScale * Bump * Gradient);
}

OutRoughness = R;
OutNormal = Nw;
OutMetallic = M;
return Col;
"""


def new_material(name):
    path = f"{FOLDER}/{name}"
    if assets.does_asset_exist(path):
        assets.delete_asset(path)
    material = tools.create_asset(name, FOLDER, unreal.Material, unreal.MaterialFactoryNew())
    # Geometry is drawn with instanced static meshes.
    material.set_editor_property("used_with_instanced_static_meshes", True)
    return material


def vector_param(material, name, default, x, y):
    node = mel.create_material_expression(material, unreal.MaterialExpressionVectorParameter, x, y)
    node.set_editor_property("parameter_name", name)
    node.set_editor_property("default_value", unreal.LinearColor(*default))
    return node


def scalar_param(material, name, default, x, y):
    node = mel.create_material_expression(material, unreal.MaterialExpressionScalarParameter, x, y)
    node.set_editor_property("parameter_name", name)
    node.set_editor_property("default_value", default)
    return node


def finish(material):
    mel.recompile_material(material)
    assets.save_loaded_asset(material)
    unreal.log(f"Configurator: saved {material.get_path_name()}")


# --- Opaque lit surface with procedural detail: walls, glass, frames, slabs, ground, trees ---
surface = new_material("M_ConfiguratorSurface")
# The relief is computed in world space (see the end of SURFACE_HLSL).
surface.set_editor_property("tangent_space_normal", False)

custom = mel.create_material_expression(surface, unreal.MaterialExpressionCustom, -350, 0)
custom.set_editor_property("description", "ProceduralSurface")
custom.set_editor_property("output_type", unreal.CustomMaterialOutputType.CMOT_FLOAT3)

input_names = ["P", "N", "BaseColor", "Rough", "Metal", "Pattern", "Yaw", "InstRand", "Bump"]
custom_inputs = []
for input_name in input_names:
    custom_input = unreal.CustomInput()
    custom_input.set_editor_property("input_name", input_name)
    custom_inputs.append(custom_input)
custom.set_editor_property("inputs", custom_inputs)

custom_outputs = []
for output_name, output_type in (("OutRoughness", unreal.CustomMaterialOutputType.CMOT_FLOAT1),
                                 ("OutNormal", unreal.CustomMaterialOutputType.CMOT_FLOAT3),
                                 ("OutMetallic", unreal.CustomMaterialOutputType.CMOT_FLOAT1)):
    custom_output = unreal.CustomOutput()
    custom_output.set_editor_property("output_name", output_name)
    custom_output.set_editor_property("output_type", output_type)
    custom_outputs.append(custom_output)
custom.set_editor_property("additional_outputs", custom_outputs)
custom.set_editor_property("code", SURFACE_HLSL)

# Position relative to the actor origin: keeps the numbers small (no large-world-coordinate types in the shader).
world_position = mel.create_material_expression(surface, unreal.MaterialExpressionWorldPosition, -1000, -300)
origin = vector_param(surface, "Origin", (0.0, 0.0, 0.0, 0.0), -1000, -150)
relative_position = mel.create_material_expression(surface, unreal.MaterialExpressionSubtract, -750, -250)
mel.connect_material_expressions(world_position, "", relative_position, "A")
mel.connect_material_expressions(origin, "", relative_position, "B")

sources = {
    "P": relative_position,
    "N": mel.create_material_expression(surface, unreal.MaterialExpressionVertexNormalWS, -750, -100),
    "BaseColor": vector_param(surface, "Color", (0.8, 0.8, 0.8, 1.0), -750, 0),
    "Rough": scalar_param(surface, "Roughness", 0.7, -750, 200),
    "Metal": scalar_param(surface, "Metallic", 0.0, -750, 300),
    "Pattern": scalar_param(surface, "Pattern", 0.0, -750, 400),
    "Yaw": scalar_param(surface, "Yaw", 0.0, -750, 500),
    "InstRand": mel.create_material_expression(surface, unreal.MaterialExpressionPerInstanceRandom, -750, 600),
    "Bump": scalar_param(surface, "Bump", 1.0, -750, 700),
}
for input_name, source in sources.items():
    if not mel.connect_material_expressions(source, "", custom, input_name):
        unreal.log_error(f"Configurator: failed to connect custom input {input_name}")

for output_name, material_property in (("", unreal.MaterialProperty.MP_BASE_COLOR),
                                       ("OutRoughness", unreal.MaterialProperty.MP_ROUGHNESS),
                                       ("OutNormal", unreal.MaterialProperty.MP_NORMAL),
                                       ("OutMetallic", unreal.MaterialProperty.MP_METALLIC)):
    if not mel.connect_material_property(custom, output_name, material_property):
        unreal.log_error(f"Configurator: failed to connect custom output '{output_name}'")
finish(surface)

# --- Translucent unlit overlay: apartment status tint and the glowing selection outline ---
overlay = new_material("M_ConfiguratorOverlay")
overlay.set_editor_property("blend_mode", unreal.BlendMode.BLEND_TRANSLUCENT)
overlay.set_editor_property("shading_model", unreal.MaterialShadingModel.MSM_UNLIT)
color = vector_param(overlay, "Color", (0.1, 0.8, 0.35, 1.0), -700, -100)
emissive = scalar_param(overlay, "Emissive", 1.0, -700, 150)
multiply = mel.create_material_expression(overlay, unreal.MaterialExpressionMultiply, -400, 0)
mel.connect_material_expressions(color, "", multiply, "A")
mel.connect_material_expressions(emissive, "", multiply, "B")
mel.connect_material_property(multiply, "", unreal.MaterialProperty.MP_EMISSIVE_COLOR)
mel.connect_material_property(scalar_param(overlay, "Opacity", 0.35, -500, 300), "", unreal.MaterialProperty.MP_OPACITY)
finish(overlay)
